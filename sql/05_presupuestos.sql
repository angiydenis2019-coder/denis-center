create table if not exists public.presupuestos (
  id              uuid primary key default gen_random_uuid(),
  numero          int generated by default as identity,   -- N° correlativo (1, 2, 3…)
  cliente_id      uuid not null references public.clientes(id),
  equipo_id       uuid references public.equipos(id),
  tecnico_id      uuid references public.perfiles(id),
  fecha           timestamptz not null default now(),
  validez_dias    int not null default 15 check (validez_dias between 1 and 365),
  estado          text not null default 'borrador'
                    check (estado in ('borrador','enviado','aceptado','rechazado')),
  trabajo_propuesto text,
  mano_obra       numeric(12,2) not null default 0 check (mano_obra >= 0),
  notas           text,
  trabajo_id      uuid references public.trabajos(id),     -- trabajo creado al aceptarlo
  eliminado       boolean not null default false,
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now()
);
create index if not exists presupuestos_cliente on public.presupuestos (cliente_id);
create index if not exists presupuestos_estado on public.presupuestos (estado) where not eliminado;

create table if not exists public.presupuesto_items (
  id              uuid primary key default gen_random_uuid(),
  presupuesto_id  uuid not null references public.presupuestos(id),
  descripcion     text not null,
  cantidad        numeric(10,2) not null default 1 check (cantidad > 0),
  precio_unitario numeric(12,2) not null default 0 check (precio_unitario >= 0),
  eliminado       boolean not null default false,
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now()
);
create index if not exists presupuesto_items_p on public.presupuesto_items (presupuesto_id);

drop trigger if exists t_presupuestos on public.presupuestos;
create trigger t_presupuestos before update on public.presupuestos
  for each row execute function public.tocar_actualizado();
drop trigger if exists t_presupuesto_items on public.presupuesto_items;
create trigger t_presupuesto_items before update on public.presupuesto_items
  for each row execute function public.tocar_actualizado();

alter table public.presupuestos enable row level security;
alter table public.presupuesto_items enable row level security;

do $$
declare tabla text;
begin
  foreach tabla in array array['presupuestos','presupuesto_items'] loop
    execute format('drop policy if exists %1$s_ver on public.%1$s', tabla);
    execute format('drop policy if exists %1$s_crear on public.%1$s', tabla);
    execute format('drop policy if exists %1$s_editar on public.%1$s', tabla);
    execute format('create policy %1$s_ver    on public.%1$s for select to authenticated using (public.es_miembro())', tabla);
    execute format('create policy %1$s_crear  on public.%1$s for insert to authenticated with check (public.es_miembro())', tabla);
    execute format('create policy %1$s_editar on public.%1$s for update to authenticated using (public.es_miembro()) with check (public.es_miembro())', tabla);
  end loop;
end $$;
